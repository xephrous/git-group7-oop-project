    private void jButton6ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton6ActionPerformed
        // TODO add your handling code here:

        String productName = jTextField1.getText().trim();
        String category = jComboBox1.getSelectedItem().toString();
        String priceText = jTextField3.getText().trim();


        if (productName.isEmpty() || category.isEmpty() || priceText.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Please fill in all product fields.");
            return;
        }


        double price;

        try {
            price = Double.parseDouble(priceText.replace("₱", "").replace(",", ""));

            if (price < 0) {
                javax.swing.JOptionPane.showMessageDialog(this,
                        "Price cannot be negative.");
                return;
            }

        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Please enter a valid price.");
            return;
        }


        javax.swing.table.DefaultTableModel model
                = (javax.swing.table.DefaultTableModel) jTable1.getModel();


        int nextNumber = 1;

        for (int i = 0; i < model.getRowCount(); i++) {
            String existingId = model.getValueAt(i, 0).toString();
            int number = Integer.parseInt(existingId.substring(4));

            if (number >= nextNumber) {
                nextNumber = number + 1;
            }
        }

        String productId = String.format("PRD-%03d", nextNumber);


        model.addRow(new Object[]{
            productId,
            productName,
            category,
            String.format("₱%.2f", price),
            "Edit / Delete"
        });

        ProductData.addProduct(
                new Product(productId, productName, category, price)
        );


        int count = model.getRowCount();
        jLabel17.setText(count + " Products registered");
        jLabel19.setText(count + " Registered Products");


        jTextField1.setText("");
        jComboBox1.setSelectedIndex(0);
        jTextField3.setText("");

        javax.swing.JOptionPane.showMessageDialog(this,
                "Product added successfully!");

    }//GEN-LAST:event_jButton6ActionPerformed

